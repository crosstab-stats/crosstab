/**
 * @file t-critical.test.mjs
 * The 95% interval an error bar draws, against the distribution it claims to use.
 *
 * ## Why this file exists
 *
 * The "95% CI" error bar was drawn as mean ± 1.96·SEM. 1.96 is the quantile of the
 * NORMAL distribution — correct when the standard deviation is known, which it never is
 * on a chart built from a handful of observations. The right multiplier is Student's t
 * on n − 1 degrees of freedom, and on the sample sizes these kinds are made for the gap
 * is not cosmetic: with three observations per group it is 4.303 against 1.96, so every
 * such interval was drawn at 46% of its true width. Nothing tested it, which is how it
 * survived; this is that test.
 *
 * ## The reference values are R's
 *
 * Produced by `qt(0.975, df)` on R 4.6.0 and pasted below, rather than computed here by
 * a second implementation — an expectation generated by the same idea it is checking is
 * not a check. The tolerance is what the shipped table and expansion are good for, and
 * is still three orders of magnitude finer than a pixel.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

const { tCritical95, errorBounds, computeStats } = await import('../core/charts/stdlib.js');

/** R 4.6.0: `qt(0.975, df)`. */
const R_QT = [
  [1, 12.706205], [2, 4.302653], [3, 3.182446], [4, 2.776445], [5, 2.570582],
  [6, 2.446912], [7, 2.364624], [8, 2.306004], [9, 2.262157], [10, 2.228139],
  [11, 2.200985], [12, 2.178813], [13, 2.160369], [14, 2.144787], [15, 2.131450],
  [16, 2.119905], [17, 2.109816], [18, 2.100922], [19, 2.093024], [20, 2.085963],
  [21, 2.079614], [22, 2.073873], [23, 2.068658], [24, 2.063899], [25, 2.059539],
  [26, 2.055529], [27, 2.051831], [28, 2.048407], [29, 2.045230], [30, 2.042272],
  [31, 2.039513], [40, 2.021075], [50, 2.008559], [60, 2.000298], [100, 1.983972],
  [120, 1.979930], [200, 1.971896], [500, 1.964720], [1000, 1.962339],
];

test('every critical value matches R to within 5e-4', () => {
  for (const [df, ref] of R_QT) {
    const got = tCritical95(df);
    assert.ok(Math.abs(got - ref) < 5e-4, `df ${df}: ${got} vs R's ${ref}`);
  }
});

test('the expansion beyond the table is the accurate half, not the ragged one', () => {
  // The seam at df = 30/31 is where a formula would be weakest, so it is the one to
  // watch: a table that stopped short of where its replacement is good would show up
  // here as a step.
  for (const [df, ref] of R_QT.filter(([d]) => d > 30)) {
    assert.ok(Math.abs(tCritical95(df) - ref) < 1e-4, `df ${df}`);
  }
  assert.ok(Math.abs(tCritical95(30) - tCritical95(31)) < 0.01, 'no step at the seam');
});

test('it never returns the normal quantile for a small sample', () => {
  // The regression test proper: the number this replaced.
  for (const df of [1, 2, 3, 5, 10]) assert.ok(tCritical95(df) > 2.2, `df ${df}`);
  assert.equal(tCritical95(2), 4.303);
});

test('a degenerate df falls back to the widest interval, not the narrowest', () => {
  // n = 1 has no interval at all; erring wide is the honest direction when the alternative
  // is drawing a confident-looking tick on one observation.
  for (const df of [0, -1, NaN, undefined]) assert.equal(tCritical95(df), 12.706);
});

// =============================================================================
// What the error bar actually draws
// =============================================================================

const THREE = [10, 12, 14]; // mean 12, sd 2, sem 1.1547

test('the 95% bound is t-based, and the old 1.96 would be visibly wrong', () => {
  const stats = computeStats(THREE);
  const { lo, hi } = errorBounds(stats, 'ci95');
  const t = tCritical95(2);
  assert.ok(Math.abs(hi - (stats.mean + t * stats.sem)) < 1e-9);
  assert.ok(Math.abs(lo - (stats.mean - t * stats.sem)) < 1e-9);
  // Against what it used to draw: more than twice as tall.
  const old = 1.96 * stats.sem;
  assert.ok((hi - stats.mean) / old > 2.1, 'the correction is the point');
});

test('SEM and SD bars are untouched', () => {
  const stats = computeStats(THREE);
  assert.deepEqual(errorBounds(stats, 'sd'), { lo: 10, hi: 14 });
  assert.deepEqual(errorBounds(stats, 'sem'), { lo: 12 - stats.sem, hi: 12 + stats.sem });
  assert.equal(errorBounds(stats, 'nope'), null);
  assert.equal(errorBounds(null, 'ci95'), null);
});

test('the CI crosses the SD as n grows, which is the whole reason to offer both', () => {
  // At n = 3 the interval around the mean is WIDER than ±1 SD; by n = 10 it is narrower.
  // A reader who thinks the two are interchangeable is wrong in both directions.
  const wide = computeStats([10, 12, 14]);
  const many = computeStats(Array.from({ length: 10 }, (_, i) => 10 + (i % 3)));
  const span = (s, type) => { const e = errorBounds(s, type); return e.hi - e.lo; };
  assert.ok(span(wide, 'ci95') > span(wide, 'sd'), 'n = 3');
  assert.ok(span(many, 'ci95') < span(many, 'sd'), 'n = 10');
});

// =============================================================================
// The new summary option, through the real kinds
// =============================================================================

await import('./chart-kinds-harness.mjs');
const { defaultView, renderChart, chartUiSpec } = await import('../core/chart-renderer.js');

/** A dot plot of one group of three, which is where the correction shows most. */
const DOTS = {
  kind: 'dots',
  title: 'Three observations',
  groups: [{ key: 'g1', label: 'Group 1', values: THREE }],
  axes: { x: { title: 'Group' }, y: { title: 'Value' } },
};

const ysOf = (svg) => [...svg.matchAll(/y[12]="([-\d.]+)"/g)].map((m) => Number(m[1]));

test('dots and violin both offer Mean + 95% CI', () => {
  for (const kind of ['dots', 'violin']) {
    const spec = chartUiSpec({ ...DOTS, kind });
    const summary = spec.controls.find((c) => c.id === 'summary');
    assert.ok(summary, `${kind} has a summary control`);
    const values = summary.options.map((o) => (Array.isArray(o) ? o[0] : o.value));
    assert.ok(values.includes('ci95'), `${kind} offers ci95: ${JSON.stringify(values)}`);
    assert.ok(values.includes('mean') && values.includes('median'), 'and keeps what it had');
  }
});

test('the CI whisker is drawn, and is taller than the SD whisker at n = 3', () => {
  const draw = (summary) => renderChart(DOTS, { ...defaultView(DOTS), summary });
  const sd = ysOf(draw('mean'));
  const ci = ysOf(draw('ci95'));
  // Same marks, so the same number of lines — only further apart.
  assert.equal(sd.length, ci.length);
  const span = (ys) => Math.max(...ys) - Math.min(...ys);
  assert.ok(span(ci) > span(sd), `ci span ${span(ci)} should exceed sd span ${span(sd)}`);
  assert.notEqual(draw('ci95'), draw('mean'));
});

test('None still draws no summary at all', () => {
  const none = renderChart(DOTS, { ...defaultView(DOTS), summary: 'none' });
  const ci = renderChart(DOTS, { ...defaultView(DOTS), summary: 'ci95' });
  assert.ok(ysOf(none).length < ysOf(ci).length);
});
